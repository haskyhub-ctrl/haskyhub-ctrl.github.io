function setupLocationDropdowns(provSelectId, wardSelectId, defaultProv = 'Tỉnh Bắc Ninh', defaultWard = '') {
    const provSelect = document.getElementById(provSelectId);
    const wardSelect = document.getElementById(wardSelectId);
    if (!provSelect || !wardSelect) return;

    // Populate provinces
    provSelect.innerHTML = VIETNAM_PROVINCES.map(p => 
        `<option value="${p}" ${p === defaultProv ? 'selected' : ''}>${p}</option>`
    ).join('');

    function updateWards(selectedProv, selectWardVal = '') {
        let wards = [];
        if (selectedProv && selectedProv.includes('Bắc Ninh')) {
            wards = BAC_NINH_WARDS;
        } else {
            wards = [
                'Phường Trung tâm', 'Phường 1', 'Phường 2', 'Xã Trung tâm', 'Thị trấn Huyện lỵ'
            ];
        }
        wardSelect.innerHTML = `<option value="">-- Chọn Xã / Phường --</option>` +
            wards.map(w => `<option value="${w}" ${w === selectWardVal ? 'selected' : ''}>${w}</option>`).join('');
    }

    provSelect.addEventListener('change', () => {
        updateWards(provSelect.value);
    });

    updateWards(defaultProv, defaultWard);
}
